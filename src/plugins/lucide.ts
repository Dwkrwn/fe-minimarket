export type IconName = keyof typeof iconMap

/** Names offered by the menu icon picker (MenuForm.vue). */
export const lucideIconNames: string[] = Object.keys(iconMap)

export function registerLucide(app: App) {
  const g = globalThis as { __LUCIDE_COMPONENTS__?: Set<string> }
  if (!g.__LUCIDE_COMPONENTS__) g.__LUCIDE_COMPONENTS__ = new Set()
  const registered = g.__LUCIDE_COMPONENTS__

  for (const [name, component] of Object.entries(iconMap)) {
    if (!registered.has(name)) {
      app.component(name, component as any)
      registered.add(name)
    }
    const prefixed = `Lucide${name}`
    if (!registered.has(prefixed)) {
      app.component(prefixed, component as any)
      registered.add(prefixed)
    }
  }
}
